"""Extract upstream numerical job body and add independently scheduled queues.
The complete upstream header and its upstream attribution remain required inputs.
"""
from pathlib import Path
import argparse, hashlib, json
p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
s=a.source.read_text();start=s.index('template <int CB, int NT, int W, int S, int LO, int HI, int EPI>\n__global__ void __launch_bounds__(W * 32, 4) grouped_cp_kernel(');end=s.index('\nstruct GroupedArgs',start)
f=s[start:end]
f=f.replace('__global__ void __launch_bounds__(W * 32, 4) grouped_cp_kernel(', '__device__ __forceinline__ void spark_cp_job(')
f=f.replace('int slots, const DecodeEpi ep) {','int slots, const DecodeEpi ep, int ur, int rem, int NY, int NZ, uint32_t* smem, int* rows_sh, int& last_sh) {')
f=f.replace('    __shared__ __align__(16) uint32_t smem[RING > RED ? RING : RED];\n    __shared__ int rows_sh[16];\n    __shared__ int last_sh;\n','')
beg=f.index('    const int NY = gridDim.y');fin=f.index('    const int nu = ucount[0];',beg)
f=f[:beg]+f[fin:]
a.output.mkdir(parents=True,exist_ok=True)
(a.output/'spark_job.cuh').write_text('// Numerical body derived from TensorFold (see LICENSES); see NOTICE. Generated by prepare_persistent.py.\n#pragma once\n#include "experts_grouped.cuh"\nnamespace tf_exl3x {\n'+f+'\n}\n')
(a.output/'experts_grouped.cuh').write_text(s)
print(json.dumps({'source_sha256':hashlib.sha256(s.encode()).hexdigest(),'job_sha256':hashlib.sha256(f.encode()).hexdigest()}))
